// Render every registered section for the current filters. Sections are
// rebuilt from scratch: the data is small and it keeps them stateless.
function update() {
  buildFilters();
  const meetings = MEETINGS.filter(inView);
  document.getElementById("count").textContent =
    `${fmtInt(meetings.length)} of ${fmtInt(MEETINGS.length)} meetings`;

  const main = document.getElementById("sections");
  main.replaceChildren();
  for (const s of SECTIONS) {
    const body = el("section", { id: s.id }, el("h2", {}, s.title), s.lede ? el("p", { class: "lede" }, s.lede) : null);
    main.append(body);
    s.render(meetings, body);
  }
  drawPending();
}

document.getElementById("byline").textContent =
  `${fmtInt(MEETINGS.length)} meetings, generated by grans on ${isoDay(GENERATED)}. ` +
  "Everything on this page is in this file; nothing is fetched.";

let resizeTimer;
window.addEventListener("resize", () => {
  clearTimeout(resizeTimer);
  resizeTimer = setTimeout(update, 200);
});
window.matchMedia("(prefers-color-scheme: dark)").addEventListener("change", update);

update();
